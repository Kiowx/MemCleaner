STRINGS: Dict[str, Dict[str, str]] = {"zh": ZH, "en": EN}

_lang = "zh"


def set_language(lang: str) -> None:
    global _lang
    if lang in STRINGS:
        _lang = lang


def get_language() -> str:
    return _lang


def t(key: str, **kwargs) -> str:
    """Look up ``key`` in the active language dict, with kwargs.format()."""
    table = STRINGS.get(_lang, ZH)
    s = table.get(key) or ZH.get(key) or key
    if kwargs:
        try:
            return s.format(**kwargs)
        except (KeyError, IndexError):
            return s
    return s


def tn(key: str, count: int, **kwargs) -> str:
    """Like :func:`t` but picks ``key + '_1'`` for English when count == 1."""
    kwargs["count"] = count
    if _lang == "en" and count == 1:
        singular_key = f"{key}_1"
        table = STRINGS.get("en", EN)
        if singular_key in table:
            return t(singular_key, **kwargs)
    return t(key, **kwargs)
